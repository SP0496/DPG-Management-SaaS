package com.pgmanagement.saas.modules.resident.controller;

import com.pgmanagement.saas.modules.resident.dto.request.AcceptInvitationRequest;
import com.pgmanagement.saas.modules.resident.dto.request.CreateInvitationRequest;
import com.pgmanagement.saas.modules.resident.dto.response.ResidentInvitationResponse;
import com.pgmanagement.saas.modules.resident.entity.InvitationStatus;
import com.pgmanagement.saas.modules.resident.service.ResidentInvitationService;
import com.pgmanagement.saas.shared.dto.ApiResponse;
import com.pgmanagement.saas.shared.dto.PagedResponse;
import com.pgmanagement.saas.shared.security.TenantContext;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.util.UUID;

@RestController
@RequestMapping("/residents")
@RequiredArgsConstructor
@Tag(name = "Residents", description = "Secure resident invitation generation and verification endpoints")
public class ResidentInvitationController {

    private final ResidentInvitationService invitationService;

    @PostMapping("/{residentProfileId}/invitations")
    @PreAuthorize("hasRole('OWNER')")
    @Operation(summary = "Generate a single-use cryptographic invitation code for a resident")
    public ResponseEntity<ApiResponse<ResidentInvitationResponse>> createInvitation(
            @PathVariable UUID residentProfileId,
            @Valid @RequestBody(required = false) CreateInvitationRequest request) {
        ResidentInvitationResponse created = invitationService.createInvitation(
                TenantContext.currentUserId(), residentProfileId, request);
        return ResponseEntity.status(HttpStatus.CREATED)
                .body(ApiResponse.success(created, "Resident invitation generated"));
    }

    @GetMapping("/invitations")
    @PreAuthorize("hasRole('OWNER')")
    @Operation(summary = "List and search invitations generated by the authenticated owner")
    public ResponseEntity<ApiResponse<PagedResponse<ResidentInvitationResponse>>> searchInvitations(
            @RequestParam(required = false) InvitationStatus status,
            @RequestParam(required = false) String search,
            @RequestParam(defaultValue = "0") int page,
            @RequestParam(defaultValue = "20") int size) {
        PagedResponse<ResidentInvitationResponse> response = invitationService.searchInvitationsForOwner(
                TenantContext.currentUserId(), status, search, page, size);
        return ResponseEntity.ok(ApiResponse.success(response));
    }

    @PatchMapping("/invitations/{invitationId}/revoke")
    @PreAuthorize("hasRole('OWNER')")
    @Operation(summary = "Revoke a pending resident invitation")
    public ResponseEntity<ApiResponse<ResidentInvitationResponse>> revokeInvitation(
            @PathVariable UUID invitationId) {
        ResidentInvitationResponse response = invitationService.revokeInvitation(
                TenantContext.currentUserId(), invitationId);
        return ResponseEntity.ok(ApiResponse.success(response, "Invitation revoked"));
    }

    @PostMapping("/me/invitations/accept")
    @PreAuthorize("hasRole('RESIDENT')")
    @Operation(summary = "Claim a resident invitation code using the verified phone account")
    public ResponseEntity<ApiResponse<ResidentInvitationResponse>> acceptInvitation(
            @Valid @RequestBody AcceptInvitationRequest request) {
        ResidentInvitationResponse response = invitationService.acceptInvitationAsResident(
                TenantContext.currentUserId(), request.getInviteCode());
        return ResponseEntity.ok(ApiResponse.success(response, "Invitation accepted"));
    }
}
